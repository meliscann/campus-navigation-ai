def build_campus_map():
    floors = [FLOOR_0, FLOOR_1, FLOOR_2, FLOOR_3, FLOOR_4, FLOOR_5]

    # Safety checks (10x24)
    for i, f in enumerate(floors):
        assert len(f) == 10, f"Floor {i} must have 10 rows"
        lens = [len(row) for row in f]
        assert all(L == 24 for L in lens), f"Floor {i} rows must be 24: {lens}"

    return [build_floor_from_strings(f) for f in floors]